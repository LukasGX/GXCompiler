namespace GXCompiler.GXLexer;

public enum TokenType
{
    Comment,
    Out,
    Shout,
    Exit,
    If,
    Else,
    Switch,
    Repeat,
    Iterate,
    While,
    Class,
    Init,
    Entrypoint,
    Method,
    Private,
    Return,
    Inst,
    Case,
    New,
    Using,
    Try,
    Treat,
    Afterwards,
    Ns,
    Default,
    Continue,
    Break,
    Literal,
    BoolLiteral,
    Str,
    Int,
    Dec,
    Bool,
    Rex,
    Number,
    Identifier,
    Plus,
    Minus,
    Multiply,
    Divide,
    Power,
    Equal,
    StrictEqual,
    NotEqual,
    Lower,
    LowerOrEqual,
    Greater,
    GreaterOrEqual,
    Not,
    Assign,
    PlusAssign,
    MinusAssign,
    MultiplyAssign,
    DivideAssign,
    PowerAssign,
    Semicolon,
    Comma,
    Dot,
    Colon,
    Hashtag,
    LeftParen,
    RightParen,
    LeftBrace,
    RightBrace,
    LeftBracket,
    RightBracket,
    EOF
}

public class Token(TokenType tokenType, string value, int line, int column)
{
    public TokenType TokenType = tokenType;
    public string Value = value;
    public int Line = line;
    public int Column = column;
}